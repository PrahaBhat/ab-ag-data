#!/usr/bin/env bash
# Self-contained ESMFold2 environment under esmfold2/ (safe to git pull on Vista).
set -euo pipefail

ESMFOLD2_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ESMFOLD2_ROOT"

PYTHON="${PYTHON:-python3}"
VENV_DIR="${VENV_DIR:-$ESMFOLD2_ROOT/.venv}"
CACHE_DIR="${CACHE_DIR:-$ESMFOLD2_ROOT/cache}"
INSTALL_CUDA_TORCH="${INSTALL_CUDA_TORCH:-1}"
PREFETCH_WEIGHTS="${PREFETCH_WEIGHTS:-0}"
TORCH_CUDA_INDEX="${TORCH_CUDA_INDEX:-https://download.pytorch.org/whl/cu124}"

echo "==> ESMFold2 root: $ESMFOLD2_ROOT"

mkdir -p \
  "$CACHE_DIR/huggingface" \
  "$CACHE_DIR/torch" \
  "$CACHE_DIR/pip" \
  "$ESMFOLD2_ROOT/outputs" \
  "$ESMFOLD2_ROOT/manifests" \
  "$ESMFOLD2_ROOT/logs"

if [[ ! -d "$VENV_DIR" ]]; then
  echo "==> Creating venv at $VENV_DIR"
  "$PYTHON" -m venv "$VENV_DIR"
fi

# shellcheck disable=SC1091
source "$VENV_DIR/bin/activate"

python -m pip install --upgrade pip wheel setuptools

if [[ "$INSTALL_CUDA_TORCH" == "1" ]]; then
  echo "==> Installing PyTorch (CUDA wheel from $TORCH_CUDA_INDEX)"
  pip install torch --index-url "$TORCH_CUDA_INDEX"
else
  echo "==> Installing PyTorch (CPU)"
  pip install torch
fi

pip install -r "$ESMFOLD2_ROOT/requirements.txt"

ENV_FILE="$ESMFOLD2_ROOT/env.sh"
cat > "$ENV_FILE" <<EOF
# Generated by setup.sh — source from repo:  source esmfold2/env.sh
export ESMFOLD2_ROOT="$ESMFOLD2_ROOT"
export VIRTUAL_ENV="$VENV_DIR"
export PATH="\$VIRTUAL_ENV/bin:\$PATH"

export HF_HOME="$CACHE_DIR/huggingface"
export HUGGINGFACE_HUB_CACHE="$CACHE_DIR/huggingface/hub"
export TRANSFORMERS_CACHE="$CACHE_DIR/huggingface/transformers"
export TORCH_HOME="$CACHE_DIR/torch"
export PIP_CACHE_DIR="$CACHE_DIR/pip"

export ESMFOLD2_MODEL_ID="\${ESMFOLD2_MODEL_ID:-biohub/ESMFold2-hf}"
export PYTHONPATH="\$ESMFOLD2_ROOT:\${PYTHONPATH:-}"
EOF

chmod +x "$ESMFOLD2_ROOT/bin/"*.py 2>/dev/null || true

if [[ ! -f "$ESMFOLD2_ROOT/config.local.yaml" ]]; then
  cp "$ESMFOLD2_ROOT/config.defaults.yaml" "$ESMFOLD2_ROOT/config.local.yaml"
  echo "==> Wrote config.local.yaml (edit max_total_length / fold_mode for your GPU)"
fi

# shellcheck disable=SC1091
source "$ENV_FILE"

python - <<'PY'
import importlib.util
print("python:", __import__("sys").executable)
for pkg in ("torch", "transformers"):
    spec = importlib.util.find_spec(pkg)
    print(pkg, "OK" if spec else "MISSING")
import torch
print("torch cuda available:", torch.cuda.is_available())
PY

if [[ "$PREFETCH_WEIGHTS" == "1" ]]; then
  echo "==> Prefetching model weights (several GB) …"
  python "$ESMFOLD2_ROOT/bin/prefetch_weights.py"
else
  echo "==> Skipping weight download (set PREFETCH_WEIGHTS=1 to prefetch now)"
fi

cat <<'MSG'

Setup complete.

  source esmfold2/env.sh
  python esmfold2/bin/manifest_csv.py          # dry-run guardrails
  PREFETCH_WEIGHTS=1 bash esmfold2/setup.sh    # download weights
  python esmfold2/bin/fold_csv.py --limit 1    # smoke test (needs GPU)

MSG
